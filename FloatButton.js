// common API

// icon - 버튼의 아이콘 구성 요소 설정

// description - description

// tooltip - 툴팁에 표시된 텍스트

// type - 버튼 유형 설정

// shape - 버튼 형상 설정

// onClick - 이벤트를 처리하도록 처리기 설정

// href - 하이퍼링크의 대상

// target - 링크된 URL을 표시할 위치를 지정함

// badge - Badge를 FloatButton에 연결합니다. 및 관련된 다른 소품은 지원되지 않음

// FloatButton.Group

// shape - 어린이의 버튼 모양 설정

// trigger - 메뉴 열기/닫기를 트리거할 수 있는 작업

// open - 메뉴가 보이는지 여부에 관계없이 트리거와 함께 사용함

// closeIcon - 닫기 버튼 아이콘 사용자 지정

// onOpenChange - 활성 메뉴 변경 시 실행되는 콜백, 트리거와 함께 사용

// FloatButton.BackTop

// duration - 맨 위로 돌아가는 시간(ms)

// targer - 스크롤 가능 영역 dom 노드를 지정함

// visibilityHighlight - BackTop 버튼은 스크롤 높이가 이 값에 도달할 때까지 표시되지 않음

// onclick - 버튼을 클릭할 때 실행할 수 있는 콜백 함수
